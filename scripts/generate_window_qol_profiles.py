"""Emit native guards from the independently verified three-build profile."""
import json
from pathlib import Path


def render(root):
    rows = json.loads((root / 'profiles/window-qol.json').read_bytes())['profiles']
    fields = ('creationRva', 'creationFnv', 'procedureRva', 'gameFullscreenRva',
              'mainWindowRva', 'windowedPreferenceGuardRva', 'mainWindowGuardRva',
              'gogClipRva', 'gogClipFnv', 'gogModeRva')
    text = ['// Generated by scripts/generate_window_qol_profiles.py; do not edit.',
            '#pragma once', '#include <cstdint>', '#include "MajestyBuildId.h"',
            'namespace WindowQoLProfiles {', 'struct Profile {', 'MajestyBuildId build;']
    text += ['std::uint32_t ' + f + ';' for f in fields]
    text += ['unsigned char preferenceGuard[19];', 'unsigned char windowGuard[12];',
             '};', 'constexpr Profile profiles[] = {']
    for key, build in (('public', 'SteamPublic'), ('beta2', 'SteamBeta2'), ('gog', 'Gog')):
        row = rows[key]
        text += ['{MajestyBuildId::' + build + ',']
        text += [','.join('0x%Xu' % row[f] for f in fields) + ',']
        for field in ('windowedPreferenceGuard', 'mainWindowGuard'):
            text += ['{' + ','.join('0x%02X' % b for b in bytes.fromhex(row[field])) + '},']
        text += ['},']
    return '\n'.join(text + ['};', '}', ''])


if __name__ == '__main__':
    root = Path(__file__).resolve().parent.parent
    (root / 'runtime/WindowQoLProfiles.h').write_text(render(root), encoding='utf-8')
